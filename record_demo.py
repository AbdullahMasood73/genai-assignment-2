"""Record the actual local browser workflow with timed explanatory captions."""
import os,time
from pathlib import Path
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parent
folder=root/".tools"/"recording"
folder.mkdir(exist_ok=True)
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path=r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",headless=True)
    ctx=browser.new_context(viewport={"width":1280,"height":900},record_video_dir=str(folder),record_video_size={"width":1280,"height":900},accept_downloads=True)
    page=ctx.new_page()
    page.goto("http://127.0.0.1:8764")
    def caption(text):
        page.evaluate("""text=>{let c=document.getElementById('demo-caption');if(!c){c=document.createElement('aside');c.id='demo-caption';Object.assign(c.style,{pointerEvents:'none',position:'fixed',bottom:'0',left:'0',right:'0',background:'#132e2c',color:'white',padding:'16px 48px',font:'20px/1.45 Segoe UI',zIndex:100});document.body.append(c)}c.textContent=text}""",text)
        page.wait_for_timeout(12000)
    def run():
        page.locator("#run").click()
        page.locator("#download").wait_for(state="visible")
    caption("Clinical trial screening • Muhammad Abdullah Masood, I230756. This demonstration runs the locally fine-tuned Pythia model on invented patient records.")
    caption("The workbench checks individual trial rules. Its overall screening outcome is a rule-based summary that requires professional review.")
    page.locator("#run").click()
    page.get_by_text("Enter a patient note and between one and thirty criteria.").wait_for()
    caption("The first submission is empty. Input validation explains what is missing and leaves the form available for correction.")
    page.locator("#example").click()
    caption("Load example fills a fictional two-sentence note. Original sentence numbers are kept so a reviewer can trace a citation back to the note.")
    caption("The two rules ask different questions. Inclusion asks whether a requirement is met. Exclusion asks whether a disqualifying condition applies.")
    page.locator("#mode").select_option("compare")
    caption("Compare all three modes runs fresh inference using the same prompt, weights and output constraints. The timings belong to this request.")
    run()
    page.locator("article").first.scroll_into_view_if_needed()
    page.screenshot(path=str(folder/"screen.png"))
    caption("Each card repeats the exact criterion and reports its predicted label. A reviewer can inspect the supporting record text when the decoder returns sentence IDs.")
    caption("A missing citation is flagged for manual review. The model can make an unsupported judgment even when its output is syntactically valid.")
    page.locator("article").last.scroll_into_view_if_needed()
    caption("The exclusion card uses the exclusion label set. A predicted exclusion is a potential conflict, while insufficient information means that the record does not resolve the rule.")
    caption("Uncached decoding reprocesses the entire prefix at each step. Cached decoding reuses prior keys and values and advances positions with each generated token.")
    caption("Speculation uses a two-block draft. The six-block target validates its proposed sequence and replaces the first disagreeing token.")
    caption("The acceptance count shows how many draft proposals the target kept. Token agreement compares the full output, including the sentence IDs.")
    with page.expect_download() as dl: page.locator("#download").click()
    assert dl.value.suggested_filename=="screening-report.txt"
    caption("Export screening report downloads a readable text file containing the criteria, model decisions, evidence and timing information.")
    page.locator("#note").fill("The patient is 62 years old. The patient takes metformin daily. No renal laboratory results were supplied.")
    page.locator("#criteria").fill("inclusion | Age at least 21 years.\ninclusion | Estimated glomerular filtration rate above 60.\nexclusion | Current use of insulin.")
    caption("Now enter an unseen note. This case supplies age and a medication, but it gives no renal lab value. These are deliberately different evidence conditions.")
    caption("Each line is an independent criterion. Mentioning metformin does not establish whether insulin is used, and missing renal results cannot prove eligibility.")
    page.locator("#mode").select_option("cached")
    run()
    page.locator("article").first.scroll_into_view_if_needed()
    caption("This pass uses cached inference alone. Here and in the benchmark, structure constrains the possible labels but never guarantees clinical correctness.")
    page.locator("article").nth(1).scroll_into_view_if_needed()
    caption("Review the renal criterion against the note. A true evidence check requires an observed value or a justified insufficient-information judgment.")
    page.locator("article").nth(2).scroll_into_view_if_needed()
    caption("Review the insulin criterion separately. A nearby medication mention is not proof that all other medications are absent.")
    page.locator("#criteria").fill("Age above 21")
    page.locator("#run").click()
    page.get_by_text("Each criterion needs inclusion or exclusion, a vertical bar, and rule text.").wait_for()
    caption("An incorrectly formatted criterion produces a specific error. The patient record remains available so the user can correct the rule.")
    page.locator("#criteria").fill("inclusion | Age above 21")
    page.locator("#mode").select_option("speculative")
    run()
    caption("Correct the rule and rerun with speculative decoding. Draft proposals accelerate generation only when verification saves more work than drafting costs.")
    page.locator("article").first.scroll_into_view_if_needed()
    caption("The comparison view is for inspecting a single request. The accompanying experiment logs contain controlled repeated timings over three length combinations.")
    caption("For evaluation, 53 unique patients were split by patient ID. Training used 37 patients, validation used eight, and eight were held back for final testing.")
    caption("The model sees patient text, the criterion and its type. Expert labels and sentence IDs supervise adaptation. Previous GPT predictions are excluded.")
    caption("Validation selected the checkpoint. The report compares the same base and adapted decoder on identical held-out examples using label and evidence metrics.")
    caption("The tiled-attention experiment separately checks a stable online softmax against full attention. Smaller intermediate matrices do not guarantee faster execution.")
    caption("In the submitted files, the split manifest records patient membership, prediction files retain row order, and benchmark logs report equality and latency.")
    caption("Use the exported screening report for review. This prototype is an educational experiment and its predictions require independent checking.")
    ctx.close()
    video=page.video.path()
    browser.close()
    print(video)

